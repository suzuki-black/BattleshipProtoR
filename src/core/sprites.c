/* sprites.c — スプライトパターン定義と一括投入。
   mode2 16x16: 前半16B=左列(cols0-7, MSB=col0) rows0-15 / 後半16B=右列(cols8-15) rows0-15。 */
#include "sprites.h"
#include "vdp.h"

/* 中実ブロック */
static const u8 pat_block[32] = {
    0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,
    0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF
};

/* 弾: 中央 6x6(cols5-10, rows5-10) */
static const u8 pat_bullet[32] = {
    0x00,0x00,0x00,0x00,0x00,0x07,0x07,0x07,0x07,0x07,0x07,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0x00,0xE0,0xE0,0xE0,0xE0,0xE0,0xE0,0x00,0x00,0x00,0x00,0x00
};

/* 敵戦闘機: 下向き▼(上辺が最も広く下へ収束)。rows0-7に三角、下半分は空。 */
static const u8 pat_fighter[32] = {
    /* 左列 rows0-15 */
    0xFF,0x7F,0x3F,0x1F,0x0F,0x07,0x03,0x01, 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    /* 右列 rows0-15 */
    0xFF,0xFE,0xFC,0xF8,0xF0,0xE0,0xC0,0x80, 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
};

void sprites_load(void) {
    vdp_sprite_pattern(SPR_BLOCK,   pat_block);
    vdp_sprite_pattern(SPR_BULLET,  pat_bullet);
    vdp_sprite_pattern(SPR_FIGHTER, pat_fighter);
}
